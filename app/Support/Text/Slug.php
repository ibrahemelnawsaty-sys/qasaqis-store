<?php

declare(strict_types=1);

namespace App\Support\Text;

use Illuminate\Support\Str;

/**
 * مولّد slug عربي→لاتيني. الـStr::slug الافتراضي ينقل العربية لكن بجودة خشنة
 * (ق→k، و→o، يُسقط ة)، فنقدّم خريطة صوتية أوضح (ق→q، و→w، ة→a) ثم ننظّف بـStr::slug.
 *
 * يُستعمل في محرّري الكتاب والمقال للتوليد التلقائي من العنوان عند الإنشاء. الناتج
 * لاتيني/أرقام قصير وفريد نسبيًّا؛ قيد الفرادة يُفرض عبر تحقّق النموذج (unique).
 */
final class Slug
{
    /** أقصى طول للناتج (عمود slug يسع 220؛ نترك هامشًا). */
    private const MAX = 200;

    /** تشكيل + تطويل تُزال قبل النقل. */
    private const DIACRITICS = ['ً', 'ٌ', 'ٍ', 'َ', 'ُ', 'ِ', 'ّ', 'ْ', 'ٰ', 'ـ'];

    /**
     * خريطة النقل الصوتي (حرف عربي → لاتيني). الحركات القصيرة لا تُكتب في العربية
     * فتغيب من الناتج (طبيعيّ في النقل الحرفي).
     *
     * @var array<string, string>
     */
    private const MAP = [
        // همزات وألفات
        'ا' => 'a', 'أ' => 'a', 'إ' => 'i', 'آ' => 'a', 'ٱ' => 'a', 'ء' => '',
        'ؤ' => 'w', 'ئ' => 'y', 'ى' => 'a', 'ة' => 'a',
        // حروف
        'ب' => 'b', 'ت' => 't', 'ث' => 'th', 'ج' => 'j', 'ح' => 'h', 'خ' => 'kh',
        'د' => 'd', 'ذ' => 'dh', 'ر' => 'r', 'ز' => 'z', 'س' => 's', 'ش' => 'sh',
        'ص' => 's', 'ض' => 'd', 'ط' => 't', 'ظ' => 'z', 'ع' => 'a', 'غ' => 'gh',
        'ف' => 'f', 'ق' => 'q', 'ك' => 'k', 'ل' => 'l', 'م' => 'm', 'ن' => 'n',
        'ه' => 'h', 'و' => 'w', 'ي' => 'y',
        // متغيّرات فارسية شائعة الاستعمال أحيانًا
        'ک' => 'k', 'ی' => 'y', 'ﻻ' => 'la', 'ۀ' => 'h',
        // أرقام عربية-هندية
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
    ];

    public static function fromTitle(string $title, string $separator = '-'): string
    {
        $text = trim($title);

        if ($text === '') {
            return '';
        }

        $text = str_replace(self::DIACRITICS, '', $text);
        $text = strtr($text, self::MAP);

        // Str::slug ينظّف: يحوّل المسافات والرموز إلى فواصل، يوحّد الأحرف الصغيرة،
        // ويُسقط أي بقايا غير لاتينية (فينقل بها ما لم تغطّه الخريطة إن أمكن).
        $slug = Str::slug($text, $separator);

        if (strlen($slug) > self::MAX) {
            $slug = rtrim(substr($slug, 0, self::MAX), $separator);
        }

        return $slug;
    }
}
